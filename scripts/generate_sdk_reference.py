FUNCTIONS = (ast.FunctionDef, ast.AsyncFunctionDef)


def parse(path):
    return ast.parse(path.read_text(encoding="utf-8-sig"), filename=str(path))


def unique(nodes, name, kinds):
    matches = [n for n in nodes if isinstance(n, kinds) and n.name == name]
    if len(matches) != 1:
        raise ValueError(
            f"Expected exactly one definition of {name}; got {len(matches)}"
        )
    return matches[0]


def cls(tree, name):
    return unique(tree.body, name, ast.ClassDef)


def method(node, name):
    return unique(node.body, name, FUNCTIONS)


def signature(node, name=None):
    args = copy.deepcopy(node.args)
    positional = args.posonlyargs + args.args
    defaults = [None] * (len(positional) - len(args.defaults)) + args.defaults
    entries = []

    def render(arg, default=None):
        text = ast.unparse(arg)
        if default is not None:
            text += (" = " if arg.annotation else "=") + ast.unparse(default)
        return text

    for i, (arg, default) in enumerate(zip(positional, defaults)):
        if i != 0 or arg.arg not in ("self", "cls"):
            entries.append(render(arg, default))
        if i + 1 == len(args.posonlyargs) and entries:
            entries.append("/")
    if args.vararg:
        entries.append("*" + render(args.vararg))
    elif args.kwonlyargs:
        entries.append("*")
    entries.extend(render(a, d) for a, d in zip(args.kwonlyargs, args.kw_defaults))
    if args.kwarg:
        entries.append("**" + render(args.kwarg))
    prefix = "async def " if isinstance(node, ast.AsyncFunctionDef) else "def "
    if name == "Entity":
        prefix = ""
    head = prefix + (name or node.name)
    suffix = (
        f" -> {ast.unparse(node.returns)}"
        if node.returns is not None and name != "Entity"
        else ""
    )
    inline = f'{head}({", ".join(entries)}){suffix}'
    if len(inline) <= 88 or not entries:
        return inline
    return head + "(\n" + "".join(f"    {entry},\n" for entry in entries) + ")" + suffix


def fence(text, lang="python"):
    ticks = "`" * max(3, 1 + max((len(x) for x in re.findall(r"`+", text)), default=0))
    return f"{ticks}{lang}\n{text}\n{ticks}"


def doc(node):
    return ast.get_docstring(node) or ""


def method_block(node, namespace=None):
    label = f"{namespace}.{node.name}" if namespace else node.name
    parts = [f"### `{label}()`", fence(signature(node))]
    if doc(node):
        parts.append(doc(node))
    return "\n\n".join(parts)


def fields(node):
    return [
        ast.unparse(n)
        for n in node.body
        if isinstance(n, ast.AnnAssign)
        and isinstance(n.target, ast.Name)
        and not n.target.id.startswith("_")
    ]


def model_block(node, module, *, inherited=(), methods=(), properties=()):
    parts = [f"### `{node.name}`", f"Import: `{module}.{node.name}`"]
    if doc(node):
        parts.append(doc(node))
    lines = [*inherited, *fields(node)]
    if lines:
        parts.append(fence("\n".join(lines)))
    for name in properties:
        prop = method(node, name)
        if not any(
            isinstance(d, ast.Name) and d.id == "property" for d in prop.decorator_list
        ):
            raise ValueError(f"{node.name}.{name} is no longer a property")
        parts.append(f"`{name}: {ast.unparse(prop.returns)}`\n\n{doc(prop)}")
    for name in methods:
        parts.append(f"**`{name}()`**\n\n{fence(signature(method(node, name)))}")
        if doc(method(node, name)):
            parts.append(doc(method(node, name)))
    return "\n\n".join(parts)


def event_discriminators(base):
    node = method(base, "get_event_type")
    matches = [
        n.value
        for n in node.body
        if isinstance(n, ast.Assign)
        and any(isinstance(t, ast.Name) and t.id == "mapping" for t in n.targets)
    ]
    if len(matches) != 1:
        raise ValueError("Cannot resolve event discriminator mapping")
    mapping = ast.literal_eval(matches[0])
    if set(EVENTS) - {"StreamEvent"} - mapping.keys():
        raise ValueError("Missing event discriminator")
    return mapping


def frontmatter(slug, title, order, version, body):
    return (
        f"---\ntitle: {title}\nslug: sdk-reference-{slug}\ncategory: sdk-reference\n"
        f"nav_order: {order}\n---\n\n{MARKER}\n\n# {title}\n\n"
        f"SDK version: `{version}`\n\n{body.strip()}\n"
    )


def build_pages(root):
    project = tomllib.loads((root / "pyproject.toml").read_text(encoding="utf-8-sig"))[
        "project"
    ]
    if project["name"] != "projectdavid" or not isinstance(project["version"], str):
        raise ValueError("Expected static projectdavid package version")
    version = project["version"]
    if not re.fullmatch(r"[A-Za-z0-9.+!_-]+", version):
        raise ValueError("Unexpected package version")
    package = root / "src" / "projectdavid"
    entity = cls(parse(package / "entity.py"), "Entity")
    init = parse(package / "__init__.py")
    imported_entity = any(
        isinstance(n, ast.ImportFrom)
        and n.module == "entity"
        and any(a.name == "Entity" and a.asname is None for a in n.names)
        for n in init.body
    )
    if not imported_entity:
        raise ValueError("Entity is no longer imported at package level")
    top_events = {
        a.name
        for n in init.body
        if isinstance(n, ast.ImportFrom) and n.module == "events"
        for a in n.names
        if a.asname is None
    }
    pages = {}
    index = [
        "`from projectdavid import Entity`",
        fence(signature(method(entity, "__init__"), "Entity")),
        "Pass the platform API key and API base URL when creating the client. "
        "The existing environment fallbacks are `ENTITIES_API_KEY`, `API_KEY` and `ENTITIES_BASE_URL`.",
        "## Reference",
    ]
    index_links = []
    for slug, title, namespace, module, class_name, approved in CLIENTS:
        prop = method(entity, namespace)
        if not any(
            isinstance(d, ast.Name) and d.id == "property" for d in prop.decorator_list
        ):
            raise ValueError(f"Entity.{namespace} is no longer a property")
        if prop.returns is None or ast.unparse(prop.returns) != class_name:
            raise ValueError(f"Entity.{namespace} return type changed")
        tree = parse(package / "clients" / f"{module}.py")
        node = cls(tree, class_name)
        parts = [f"Access through `client.{namespace}`.", "## Methods"]
        for name in approved.split():
            parts.append(method_block(method(node, name), f"client.{namespace}"))
        if slug == "streaming":
            parts.insert(
                1,
                "Obtain a fresh wrapper for each request and keep it in a local variable. "
                "For registered BYOK, pass `provider_key_id` to `setup()`; do not also supply a direct provider key.",
            )
            if "provider_key_id" not in [
                a.arg
                for a in method(node, "setup").args.args
                + method(node, "setup").args.kwonlyargs
            ]:
                raise ValueError("Native registered BYOK setup is missing")
        if slug == "vector-stores":
            parts.insert(
                1,
                "Use `get_or_create_file_search_store()` without a user ID for hosted self-service. "
                "Explicit cross-user operations are administrative and outside this reference.",
            )
        if slug == "execution-accounting":
            parts.append("## Response models")
            parts.extend(
                model_block(cls(tree, n), "projectdavid.clients.runs")
                for n in LEDGER_MODELS
            )
        if slug == "mcp":
            parts.append("## Discovery types")
            parts.append(
                model_block(
                    cls(tree, "McpDiscoveredTool"),
                    "projectdavid.clients.mcp_client",
                    properties=("name", "description"),
                )
            )
            parts.append(
                model_block(
                    cls(tree, "McpToolDiscoveryPage"), "projectdavid.clients.mcp_client"
                )
            )
            parts.append(
                model_block(
                    cls(tree, "McpToolCollection"),
                    "projectdavid.clients.mcp_client",
                    methods=("get", "select", "names", "definitions", "canonical_ids"),
                )
            )
        order = 102 + len(pages) + (len(pages) >= 2)
        pages[f"sdk-reference-{slug}.md"] = frontmatter(
            slug, title, order, version, "\n\n".join(parts)
        )
        index_links.append(f"- [{title}](/docs/sdk-reference-{slug})")
        if slug == "streaming":
            index_links.append("- [Streaming events](/docs/sdk-reference-events)")
    tree = parse(package / "events.py")
    base = cls(tree, "StreamEvent")
    mapping = event_discriminators(base)
    parts = [
        "Events are returned by the typed streaming interface. Import paths below reflect the source. "
        "Computer-related event types are listed as stream contracts, not as a standalone computer API."
    ]
    for name in EVENTS:
        node = cls(tree, name)
        module = "projectdavid" if name in top_events else "projectdavid.events"
        if name == "StreamEvent":
            parts.append(
                model_block(node, module, methods=("to_dict", "get_event_type"))
            )
        elif name == "ToolCallRequestEvent":
            constructor = method(node, "__init__")
            # Only expose attributes actually assigned to public self fields.
            all_args = constructor.args.posonlyargs + constructor.args.args
            args = {a.arg: a for a in all_args}
            defaults = dict(
                zip(
                    [a.arg for a in all_args][-len(constructor.args.defaults) :],
                    constructor.args.defaults,
                )
            )
            lines = fields(base)
            for statement in constructor.body:
                if not isinstance(statement, ast.Assign) or len(statement.targets) != 1:
                    continue
                target = statement.targets[0]
                if not (
                    isinstance(target, ast.Attribute)
                    and isinstance(target.value, ast.Name)
                    and target.value.id == "self"
                    and not target.attr.startswith("_")
                ):
                    continue
                value = statement.value
                if (
                    isinstance(value, ast.Name)
                    and value.id in args
                    and args[value.id].annotation
                ):
                    line = f"{target.attr}: {ast.unparse(args[value.id].annotation)}"
                    if value.id in defaults:
                        line += f" = {ast.unparse(defaults[value.id])}"
                    lines.append(line)
                elif isinstance(value, ast.Constant):
                    lines.append(
                        f"{target.attr}: {type(value.value).__name__} = {ast.unparse(value)}"
                    )
                else:
                    raise ValueError(f"Cannot resolve public field {target.attr}")
            parts.append(
                model_block(
                    node, module, inherited=lines, methods=("execute", "to_dict")
                )
            )
            parts.append(
                "The SDK creates this event; call `execute()` with a local handler rather than constructing it manually."
            )
        else:
            methods = ("execute_intercepted",) if name == "ToolInterceptEvent" else ()
            parts.append(
                model_block(node, module, inherited=fields(base), methods=methods)
            )
        if name in mapping:
            parts.append(f"Serialization type: `{mapping[name]}`")
    pages["sdk-reference-events.md"] = frontmatter(
        "events", "Streaming events", 104, version, "\n\n".join(parts)
    )
    index.append("\n".join(index_links))
    pages["sdk-reference-client.md"] = frontmatter(
        "client", "Client configuration", 101, version, "\n\n".join(index)
    )
    return pages


def publish(pages, output, *, check=False):
    if output.is_symlink():
        raise ValueError(f"Refusing symlinked output directory: {output}")
    existing = set(output.glob("*.md")) if output.exists() else set()
    expected = {output / name for name in pages}
    for path in existing:
        if path.is_symlink() or MARKER not in path.read_text(encoding="utf-8-sig"):
            raise ValueError(
                f"Refusing to overwrite or remove handwritten file: {path}"
            )
    if check:
        if existing != expected or any(
            (output / name).read_text(encoding="utf-8") != text
            for name, text in pages.items()
        ):
            raise ValueError("Generated SDK reference is stale")
        return
    output.mkdir(parents=True, exist_ok=True)
    for name, text in pages.items():
        (output / name).write_bytes(text.encode("utf-8"))
    for stale in existing - expected:
        stale.unlink()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("sdk_root", type=Path)
    parser.add_argument(
        "output", type=Path, help="Dedicated generated Markdown directory"
    )
    parser.add_argument("--check", action="store_true", help="Check without writing")
    args = parser.parse_args()
    pages = build_pages(args.sdk_root)
    publish(pages, args.output, check=args.check)
    print(
        f'{"Verified" if args.check else "Generated"} {len(pages)} SDK reference pages: {args.output}'
    )


if __name__ == "__main__":
    main()
